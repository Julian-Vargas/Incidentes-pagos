4.1 Regla general
Si solo una entidad reporta demora y han transcurrido menos de 30 minutos
desde el primer reporte, continuar monitoreo. A partir de 30 minutos,
recomendar escalamiento a Coordinación de Pagos.

4.2 Excepción por múltiples entidades
Si dos o más entidades distintas reportan demoras en el mismo incidente,
recomendar escalamiento inmediato a Coordinación de Pagos.

4.3 Escalamiento
El operador humano valida la recomendación y decide si la comunica.
